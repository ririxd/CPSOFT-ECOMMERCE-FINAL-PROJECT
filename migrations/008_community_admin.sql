ALTER TABLE users ADD COLUMN IF NOT EXISTS banned BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS admin_sessions (
    token_hash TEXT PRIMARY KEY, expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS account_flags (
    account_id BIGINT PRIMARY KEY REFERENCES registered_accounts(id) ON DELETE CASCADE,
    banned BOOLEAN NOT NULL DEFAULT FALSE, reason TEXT NOT NULL DEFAULT '',
    updated_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS support_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES registered_accounts(id) ON DELETE CASCADE,
    subject TEXT NOT NULL, message TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open',
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL REFERENCES registered_accounts(id) ON DELETE CASCADE,
    seller_id BIGINT NOT NULL REFERENCES registered_accounts(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL, UNIQUE (buyer_id, seller_id)
);
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES registered_accounts(id) ON DELETE CASCADE,
    body TEXT NOT NULL, created_at BIGINT NOT NULL
);
