CREATE TABLE IF NOT EXISTS inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES sellers(id) ON DELETE CASCADE,
    item_id BIGINT NOT NULL REFERENCES listed_items(id) ON DELETE CASCADE,
    checkout_id BIGINT REFERENCES checkouts(id) ON DELETE SET NULL,
    quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
    reason TEXT NOT NULL CHECK (reason IN ('opening_stock', 'stock_adjustment', 'sale')),
    note TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL DEFAULT ((extract(epoch FROM clock_timestamp()) * 1000)::bigint)
);
CREATE INDEX IF NOT EXISTS inventory_movements_seller_created
    ON inventory_movements (seller_id, created_at DESC);
CREATE INDEX IF NOT EXISTS checkout_items_item ON checkout_items (item_id);
